def resolve_docs(args) -> tuple[Path, str]:
    if args.repo:
        repo = Path(args.repo).expanduser()
    elif args.venture:
        repo = Path(args.ventures_base).expanduser() / args.venture
    else:
        die("target the repo with --venture <slug> or --repo <path>")
    repo = repo.resolve()  # so repo.name is the real dir (slug) even for --repo .
    if not repo.is_dir():
        die(f"repo not found: {repo}")
    docs = repo / "docs"
    if not docs.is_dir():
        die(f"no docs/ in {repo}")
    # A repo may intentionally have a human-readable directory name.  Keep the
    # stable satellite identity independent from that path when explicitly set.
    return docs, args.slug or repo.name


def main() -> int:
    ap = argparse.ArgumentParser(description="Deterministic docs/ registry + linter for a venture repo.")
    sub = ap.add_subparsers(dest="cmd", required=True)
    for name in ("index", "lint", "backfill", "brain-link", "brain-link-lint"):
        sp = sub.add_parser(name)
        sp.add_argument("--venture", help="venture slug (dir under --ventures-base)")
        sp.add_argument("--repo", help="explicit repo root (overrides --venture)")
        sp.add_argument("--slug", help="stable satellite identity (overrides repo directory name)")
        sp.add_argument("--ventures-base", default=str(Path.home() / "ventures"),
                        help="override ventures root (testing)")
        sp.add_argument("--satellite-kind", choices=("venture", "build"), default="venture",
                        help="brain registry kind (default: venture; use build for ~/builds repos)")
        if name in ("index", "backfill", "brain-link"):
            sp.add_argument("--write", action="store_true", help="write changes (else dry-run to stdout)")
        if name == "backfill":
            sp.add_argument("--refresh", action="store_true",
                            help="recompute title/summary/status from the body even if frontmatter exists")
        if name in ("brain-link", "brain-link-lint"):
            sp.add_argument("--brain", default=str(Path.home() / "second-brain"),
                            help="second-brain root (testing override)")
    args = ap.parse_args()

    docs, slug = resolve_docs(args)
    if args.cmd == "index":
        return cmd_index(docs, slug, args.write, args.satellite_kind)
    if args.cmd == "lint":
        return cmd_lint(docs, slug, args.satellite_kind)
    if args.cmd == "backfill":
        return cmd_backfill(docs, args.write, args.refresh)
    if args.cmd == "brain-link":
        return cmd_brain_link(docs, slug, resolve_brain(args), args.write, args.satellite_kind)
    if args.cmd == "brain-link-lint":
        return cmd_brain_link_lint(docs, slug, resolve_brain(args), args.satellite_kind)
    return 2


if __name__ == "__main__":
    sys.exit(main())
