def brain_link_path(brain: Path, slug: str, satellite_kind: str = "venture") -> Path:
    """Stable, non-.md link path so sb.py never treats the generated catalog as a wiki page."""
    return brain / "wiki" / "personal" / f"{satellite_kind}s" / f"{slug}.docs-index"


def resolve_brain(args) -> Path:
    brain = Path(args.brain).expanduser().resolve()
    if not brain.is_dir():
        die(f"brain not found: {brain}")
    if not (brain / "wiki").is_dir():
        die(f"no wiki/ in brain: {brain}")
    return brain


def cmd_brain_link(docs_dir: Path, slug: str, brain: Path, write: bool,
                   satellite_kind: str = "venture") -> int:
    source = docs_dir / "index.md"
    if not source.is_file():
        print("ERR  docs/index.md missing (run: docs_index.py index --write)")
        return 1
    link = brain_link_path(brain, slug, satellite_kind)
    target = Path(os.path.relpath(source.resolve(), start=link.parent))

    if link.is_symlink():
        if link.resolve() == source.resolve():
            print(f"brain docs index link: ok {link} -> {target}")
            return 0
        print(f"ERR  brain docs index link points elsewhere: {link} -> {link.readlink()}")
        return 1
    if link.exists():
        print(f"ERR  brain docs index artifact must be a symlink, not a copied file: {link}")
        return 1
    if not write:
        print(f"would create brain docs index link: {link} -> {target}")
        return 0

    link.parent.mkdir(parents=True, exist_ok=True)
    link.symlink_to(target)
    print(f"created brain docs index link: {link} -> {target}")
    return 0


def cmd_brain_link_lint(docs_dir: Path, slug: str, brain: Path,
                        satellite_kind: str = "venture") -> int:
    source = docs_dir / "index.md"
    link = brain_link_path(brain, slug, satellite_kind)
    errors: list[str] = []
    if not source.is_file():
        errors.append("docs/index.md missing (run: docs_index.py index --write)")
    if not link.is_symlink():
        errors.append(f"brain docs index artifact must be a symlink: {link}")
    elif not link.exists():
        errors.append(f"brain docs index symlink is broken: {link} -> {link.readlink()}")
    elif source.is_file() and link.resolve() != source.resolve():
        errors.append(f"brain docs index symlink points elsewhere: {link} -> {link.readlink()}")

    for error in errors:
        print(f"ERR  {error}")
    if errors:
        return 1
    print(f"brain docs index link: GREEN ({link} -> {link.readlink()})")
    return 0


