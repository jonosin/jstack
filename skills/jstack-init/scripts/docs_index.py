#!/usr/bin/env python3
"""docs_index.py — deterministic file registry + linter for a venture's docs/.

Mirrors the second-brain's `sb.py index`/`check` for a venture repo's `docs/` tree:
regenerates `docs/index.md` (a router that says what every durable planning/research
doc is about, grouped by zone) and lints naming + frontmatter so a cold agent can
navigate the docs without opening every file. The index is GENERATED — never
hand-edited — so it can never drift from the tree.

Canonical durable zone (indexed):
  docs/strategy/*.md            strategy and architecture name: YYYY-MM-DD-kebab-topic.md

Legacy zones (indexed, never new destinations):
  docs/build/*.md               prior code/build artifacts
  docs/superpowers/**           prior planning material
  docs/decisions.md             operational log          (linked, not itemized)

Unindexed zones:
  docs/scratch/**               legacy working drops; preserve, do not add new files
  ../.scratch/**                configured local tracker's specs/tickets (outside docs/)

Per-doc frontmatter (lightweight, agent-native — the index reads THIS, never the body):
  title:   human title
  summary: one line — what the doc is about + its verdict/state
  status:  active | accepted | proposed | draft | superseded | deprecated | archived
  (optional) type, created, updated, supersedes, superseded_by

Subcommands:
  index [--write]     regenerate docs/index.md from frontmatter (stdout unless --write)
  lint                validate naming + frontmatter + supersession + index freshness (exit 1 on error)
  backfill [--write]  add missing frontmatter (title<-H1, summary<-first prose line,
                      status<-parsed or 'active'); safe + idempotent
  brain-link [--write] create the brain-visible symlink to this canonical index
  brain-link-lint     validate that the brain-visible artifact is a working symlink, never a copy

Target the repo with --venture <slug> (under --ventures-base) or --repo <path>.
Use --slug <slug> to override the repo directory name when a repository has a
human-readable path but needs a stable satellite/brain identity.
Pass `--satellite-kind build` for a BUILD repo so its brain-visible index lives under
`wiki/personal/builds/`; the default remains `venture` for compatibility.
Determinism: sorted, stable output; no LLM. Same input tree -> same index bytes.

Usage:
  docs_index.py index  --write --venture second-brain-agency
  docs_index.py lint          --venture second-brain-agency
  docs_index.py backfill --write --repo /tmp/v/second-brain-agency   # testing override
  docs_index.py index --write --repo "~/builds/Fopus StudyWorld" --slug fopus-studyworld
"""
from __future__ import annotations

import argparse
import os
import re
import sys
from datetime import date
from pathlib import Path

# ---------------------------------------------------------------------------
# constants
# ---------------------------------------------------------------------------

ADR_RE = re.compile(r"^(\d{4})-[a-z0-9][a-z0-9-]*\.md$")
SPEC_RE = re.compile(r"^(\d{4}-\d{2}-\d{2})-[a-z0-9][a-z0-9-]*\.md$")

# live == the decision/doc is in force. superseded/deprecated/archived == historical.
VALID_STATUS = {"active", "accepted", "proposed", "draft",
                "superseded", "deprecated", "archived"}
LIVE_STATUS = {"active", "accepted", "proposed", "draft"}
REQUIRED_KEYS = ("title", "summary", "status")

GEN_MARK = "<!-- GENERATED by docs_index.py — do not hand-edit -->"

META_KEY_RE = re.compile(
    r"^\**\s*(status|date|deciders?|relates?-to|lineage|evidence(\s+base)?|"
    r"artifact|purpose|source(\s+clips)?|updated|created|author|tags|scope)\b", re.I)


# ---------------------------------------------------------------------------
# tiny helpers
# ---------------------------------------------------------------------------

def die(msg: str, code: int = 1) -> None:
    print(f"error: {msg}", file=sys.stderr)
    sys.exit(code)


def split_frontmatter(text: str):
    """Return (fm_text, body). fm_text is '' when there is no leading --- block."""
    if text.startswith("---\n") or text.startswith("---\r\n"):
        end = text.find("\n---", 3)
        if end != -1:
            fm = text[text.find("\n") + 1:end]
            rest = text[end + len("\n---"):]
            rest = rest.lstrip("\r")
            if rest.startswith("\n"):
                rest = rest[1:]
            return fm, rest
    return "", text


def fm_get(fm: str, key: str):
    for line in fm.splitlines():
        m = re.match(rf"^{re.escape(key)}\s*:\s*(.*)$", line)
        if m:
            v = m.group(1).strip()
            if len(v) >= 2 and v[0] in "\"'" and v[-1] == v[0]:
                v = v[1:-1].replace('\\"', '"').replace("\\\\", "\\")
            return v
    return None


def first_h1(body: str) -> str:
    for raw in body.splitlines():
        line = raw.strip()
        if line.startswith("# "):
            return line[2:].strip()
    for raw in body.splitlines():          # fallback: any heading
        line = raw.strip()
        if line.startswith("#"):
            return line.lstrip("#").strip()
    return ""


def _collect_para(lines: list[str]) -> str:
    """Collect the first sentence-like paragraph from a run of raw lines.
    A start line must be at column 0 (indented lines are wrapped continuations of
    metadata/bullets), non-heading, non-metadata, non-list, and sentence-like."""
    started = False
    para: list[str] = []
    for raw in lines:
        line = raw.strip()
        if not started:
            if not line or line == "---":
                continue
            if raw[:1].isspace():                       # indented => a wrapped continuation
                continue
            if line.startswith(("#", "!", ">", "|", "```", "<", "- ", "* ", "1.")):
                continue
            if META_KEY_RE.match(line):
                continue
            if "·" in line and re.search(r"status\s*:", line, re.I):
                continue
            if not re.match(r"^[A-Z\"']", line):        # must look like a sentence start
                continue
            started = True
            para.append(line)
        else:
            if not line or line.startswith(("#", "|", "```", ">", "- ", "* ")):
                break
            para.append(line)
    text = " ".join(para)
    text = re.sub(r"!?\[([^\]]*)\]\([^)]*\)", r"\1", text)   # links/images -> text
    text = re.sub(r"[*_`]+", "", text)                        # emphasis
    text = " ".join(text.split())
    if not text:
        return ""
    m = re.search(r"(.+?[.!?])(?:\s|$)", text)
    if m and len(m.group(1)) >= 40:
        return m.group(1).strip()
    return text


def first_prose_paragraph(body: str) -> str:
    """Prefer prose after the first '## ' section heading (skips the title +
    metadata preamble reliably); fall back to the first prose anywhere in the body."""
    lines = body.splitlines()
    start = 0
    for i, raw in enumerate(lines):
        if raw.strip().startswith("## "):
            start = i + 1
            break
    for region in (lines[start:], lines):
        para = _collect_para(region)
        if para:
            return para
    return ""


LABEL_RE = re.compile(r"^\s*-?\s*\*{0,2}(context|purpose|summary|problem)\*{0,2}\s*:\s*(.*)$", re.I)


def _first_sentence(text: str) -> str:
    text = re.sub(r"!?\[([^\]]*)\]\([^)]*\)", r"\1", text)
    text = re.sub(r"[*_`]+", "", text)
    text = " ".join(text.split())
    if not text:
        return ""
    m = re.search(r"(.+?[.!?])(?:\s|$)", text)
    return m.group(1).strip() if (m and len(m.group(1)) >= 40) else text


def labeled_summary(body: str) -> str:
    """Use an explicit Context:/Purpose:/Summary:/Problem: field (+ its indented
    wrapped continuation) when present — the cleanest one-line gist for bullet-metadata docs."""
    lines = body.splitlines()
    for i, raw in enumerate(lines):
        m = LABEL_RE.match(raw)
        if m:
            parts = [m.group(2).strip()]
            for cont in lines[i + 1:]:
                if not cont.strip() or not cont[:1].isspace():   # stop at blank or a col-0 line
                    break
                parts.append(cont.strip())
            return _first_sentence(" ".join(parts))
    return ""


def derive_summary(body: str) -> str:
    return labeled_summary(body) or first_prose_paragraph(body)


def truncate(s: str, n: int = 200) -> str:
    s = " ".join((s or "").split())
    if len(s) <= n:
        return s
    return s[:n].rsplit(" ", 1)[0].rstrip(",.;:") + "…"


def yaml_quote(s: str) -> str:
    return '"' + (s or "").replace("\\", "\\\\").replace('"', '\\"') + '"'


def parse_existing_status(body: str):
    head = "\n".join(body.splitlines()[:20])
    m = re.search(r"status\s*[:=]\s*([A-Za-z]+)", head, re.I)
    return m.group(1).lower() if m else None


def parse_existing_date(body: str):
    head = "\n".join(body.splitlines()[:20])
    m = re.search(r"date\s*[:=]?\s*\**\s*(\d{4}-\d{2}-\d{2})", head, re.I)
    if m:
        return m.group(1)
    m = re.search(r"(\d{4}-\d{2}-\d{2})", head)
    return m.group(1) if m else None


def infer_type(name: str, zone: str) -> str:
    if zone == "legacy-adr":
        return "adr"
    if zone == "strategy":
        return "strategy"
    if zone == "legacy-build":
        return "build"
    low = name.lower()
    for kw in ("premortem", "research", "design"):
        if kw in low:
            return kw
    return "spec"


