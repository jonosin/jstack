# doc model
# ---------------------------------------------------------------------------

def load_doc(path: Path, zone: str) -> dict:
    text = path.read_text()
    fm, body = split_frontmatter(text)
    title = fm_get(fm, "title") or first_h1(body) or path.stem
    summary = fm_get(fm, "summary") or truncate(derive_summary(body)) or "(no summary)"
    status = (fm_get(fm, "status") or parse_existing_status(body) or "").lower()
    return {
        "path": path, "zone": zone, "name": path.name,
        "title": title, "summary": summary, "status": status,
        "type": fm_get(fm, "type") or infer_type(path.name, zone),
        "supersedes": fm_get(fm, "supersedes"),
        "superseded_by": fm_get(fm, "superseded_by"),
        "has_fm": bool(fm.strip()),
        "fm": fm, "body": body,
    }


def collect(docs_dir: Path):
    adr_dir = docs_dir / "superpowers" / "adr"
    spec_dir = docs_dir / "superpowers" / "specs"
    strategy_dir = docs_dir / "strategy"
    build_dir = docs_dir / "build"
    legacy_adrs = [load_doc(p, "legacy-adr") for p in sorted(adr_dir.glob("*.md"))]
    legacy_specs = [load_doc(p, "legacy-spec") for p in sorted(spec_dir.glob("*.md"))]
    strategy = [load_doc(p, "strategy") for p in sorted(strategy_dir.glob("*.md"))]
    legacy_build = [load_doc(p, "legacy-build") for p in sorted(build_dir.glob("*.md"))]
    return strategy, legacy_build, legacy_adrs, legacy_specs


def legacy_scratch_count(docs_dir: Path) -> int:
    d = docs_dir / "scratch"
    if not d.is_dir():
        return 0
    return sum(1 for p in d.rglob("*") if p.is_file() and p.name != ".gitkeep")


# ---------------------------------------------------------------------------
# index rendering
# ---------------------------------------------------------------------------

def status_cell(d: dict) -> str:
    st = d["status"] or "?"
    if st in ("superseded", "deprecated") and d.get("superseded_by"):
        return f"{st} → {d['superseded_by']}"
    return st


def render_index(docs_dir: Path, slug: str, strategy, legacy_build, legacy_adrs, legacy_specs,
                 satellite_kind: str = "venture") -> str:
    def rel(p: Path) -> str:
        return p.relative_to(docs_dir).as_posix()

    L: list[str] = []
    target = f"--venture {slug}" if satellite_kind == "venture" else "--repo . --satellite-kind build"
    L.append("# docs/ — file registry (generated)")
    L.append("")
    L.append(f"> {GEN_MARK}")
    L.append("> Regenerate after ANY add/edit under `docs/`:")
    L.append(f">     python3 ~/jstack/skills/jstack-init/scripts/docs_index.py index --write {target}")
    L.append("> Lint: `docs_index.py lint`. Naming + frontmatter convention: `docs/CLAUDE.md`.")
    L.append("> Canonical workspace artifacts live here; the brain exposes this index by symlink only.")
    L.append(f"> Brain-visible no-drift reference: `~/second-brain/wiki/personal/{satellite_kind}s/{slug}.docs-index` (symlink to this file).")
    L.append("")

    def render_dated_section(heading: str, docs: list[dict], what: str) -> None:
        L.append(heading)
        L.append("")
        if docs:
            L.append(f"| Date | Doc | Status | {what} |")
            L.append("|------|-----|--------|------------|")
            for d in sorted(docs, key=lambda x: x["name"], reverse=True):
                m = SPEC_RE.match(d["name"])
                dt = m.group(1) if m else "—"
                L.append(f"| {dt} | [{d['title']}]({rel(d['path'])}) | {status_cell(d)} | {d['summary']} |")
        else:
            L.append("_(none yet)_")
        L.append("")

    render_dated_section(
        "## Strategy — `strategy/`  ·  name: `YYYY-MM-DD-kebab-topic.md`",
        strategy, "What it decides")
    L.append("## Legacy build material — `build/` (preserved)")
    L.append("")
    L.append("Historical technical decisions and design records. Do not add new files here; new durable rationale belongs in `strategy/`.")
    L.append("")
    render_dated_section(
        "### Historical build records",
        legacy_build, "What it is")

    L.append("## Legacy planning material — `superpowers/` (preserved)")
    L.append("")
    if legacy_adrs:
        L.append("### Legacy decisions — `superpowers/adr/`  ·  name: `NNNN-kebab-topic.md`")
        L.append("")
        L.append("| # | Doc | Status | What it decides |")
        L.append("|---|-----|--------|-----------------|")
        for d in sorted(legacy_adrs, key=lambda x: x["name"]):
            num = d["name"][:4]
            L.append(f"| {num} | [{d['title']}]({rel(d['path'])}) | {status_cell(d)} | {d['summary']} |")
    else:
        L.append("_(none yet)_")
    L.append("")
    L.append("### Legacy specs, designs & research — `superpowers/specs/`  ·  name: `YYYY-MM-DD-kebab-topic.md`")
    L.append("")
    if legacy_specs:
        L.append("| Date | Doc | Status | What it is |")
        L.append("|------|-----|--------|------------|")
        for d in sorted(legacy_specs, key=lambda x: x["name"], reverse=True):
            m = SPEC_RE.match(d["name"])
            dt = m.group(1) if m else "—"
            L.append(f"| {dt} | [{d['title']}]({rel(d['path'])}) | {status_cell(d)} | {d['summary']} |")
    else:
        L.append("_(none yet)_")
    L.append("")

    L.append("## Operational log")
    L.append("")
    L.append("- [decisions.md](decisions.md) — append-only operational decision log "
             "(repo/process/tooling choices only).")
    L.append("")
    L.append("## Unindexed working areas")
    L.append("")
    n = legacy_scratch_count(docs_dir)
    L.append(f"- `scratch/` — {n} legacy working file(s), preserved and not indexed. Do not add new files here.")
    L.append("- `../.scratch/` — local tracker specs/tickets when that tracker is configured; outside this registry.")
    L.append("")
    return "\n".join(L)


# ---------------------------------------------------------------------------
# subcommands
# ---------------------------------------------------------------------------

def cmd_index(docs_dir: Path, slug: str, write: bool, satellite_kind: str = "venture") -> int:
    strategy, legacy_build, legacy_adrs, legacy_specs = collect(docs_dir)
    out = render_index(docs_dir, slug, strategy, legacy_build, legacy_adrs, legacy_specs, satellite_kind)
    target = docs_dir / "index.md"
    if write:
        target.write_text(out)
        legacy_count = len(legacy_build) + len(legacy_adrs) + len(legacy_specs)
        print(f"wrote {target}  ({len(strategy)} strategy, {legacy_count} legacy)")
    else:
        sys.stdout.write(out)
    return 0


def cmd_lint(docs_dir: Path, slug: str, satellite_kind: str = "venture") -> int:
    strategy, legacy_build, legacy_adrs, legacy_specs = collect(docs_dir)
    docs = strategy + legacy_build + legacy_adrs + legacy_specs
    errors: list[str] = []
    warnings: list[str] = []
    adr_nums = {d["name"][:4] for d in legacy_adrs}

    for d in docs:
        rel = d["path"].relative_to(docs_dir).as_posix()
        # naming
        if d["zone"] == "strategy" and not SPEC_RE.match(d["name"]):
            errors.append(f"{rel}: filename must match YYYY-MM-DD-kebab-topic.md")
        elif d["zone"] == "legacy-adr" and not ADR_RE.match(d["name"]):
            warnings.append(f"{rel}: legacy ADR filename does not match NNNN-kebab-topic.md")
        elif d["zone"] in ("legacy-spec", "legacy-build") and not SPEC_RE.match(d["name"]):
            warnings.append(f"{rel}: legacy filename does not match YYYY-MM-DD-kebab-topic.md")
        # frontmatter presence
        if not d["has_fm"]:
            message = f"{rel}: missing YAML frontmatter (run: docs_index.py backfill --write)"
            (errors if d["zone"] == "strategy" else warnings).append(message)
            continue
        for k in REQUIRED_KEYS:
            if not fm_get(d["fm"], k):
                message = f"{rel}: frontmatter missing required key '{k}'"
                (errors if d["zone"] == "strategy" else warnings).append(message)
        # status vocab
        if d["status"] and d["status"] not in VALID_STATUS:
            message = f"{rel}: status '{d['status']}' not in {sorted(VALID_STATUS)}"
            (errors if d["zone"] == "strategy" else warnings).append(message)
        # supersession integrity
        if d["status"] in ("superseded", "deprecated") and not d["superseded_by"]:
            message = f"{rel}: status={d['status']} requires a superseded_by: pointer"
            (errors if d["zone"] == "strategy" else warnings).append(message)
        if d["zone"] == "legacy-adr" and d["superseded_by"]:
            ref = re.sub(r"\D", "", d["superseded_by"])[:4].zfill(4)
            if ref not in adr_nums:
                warnings.append(f"{rel}: superseded_by '{d['superseded_by']}' matches no ADR number")
        if d["summary"] == "(no summary)":
            warnings.append(f"{rel}: empty summary")

    # index freshness
    target = docs_dir / "index.md"
    expected = render_index(docs_dir, slug, strategy, legacy_build, legacy_adrs, legacy_specs, satellite_kind)
    if not target.exists():
        errors.append("index.md missing (run: docs_index.py index --write)")
    elif target.read_text() != expected:
        errors.append("index.md is stale (run: docs_index.py index --write)")

    for w in warnings:
        print(f"WARN {w}")
    for e in errors:
        print(f"ERR  {e}")
    print(f"\n{len(docs)} doc(s) checked · {len(errors)} error(s) · {len(warnings)} warning(s)")
    return 1 if errors else 0


CORE_KEYS = ("title", "summary", "status", "type", "created", "updated")


def cmd_backfill(docs_dir: Path, write: bool, refresh: bool) -> int:
    strategy, legacy_build, legacy_adrs, legacy_specs = collect(docs_dir)
    today = date.today().isoformat()
    changed = 0
    for d in strategy + legacy_build + legacy_adrs + legacy_specs:
        path = d["path"]
        rel = path.relative_to(docs_dir).as_posix()
        fm, body = d["fm"], d["body"]

        # values derived fresh from the body prose (source of truth)
        raw_status = (fm_get(fm, "status") or parse_existing_status(body) or "active").lower()
        m = SPEC_RE.match(path.name)
        derived = {
            "title": first_h1(body) or path.stem,
            "summary": truncate(derive_summary(body)) or "(no summary)",
            # normalize any out-of-vocab parsed status (e.g. 'durable', 'finalized')
            "status": raw_status if raw_status in VALID_STATUS else "active",
            "type": infer_type(path.name, d["zone"]),
            "created": (m.group(1) if m else None) or parse_existing_date(body) or today,
            "updated": today,
        }

        missing = [k for k in CORE_KEYS if fm_get(fm, k) is None]
        if d["has_fm"] and not missing and not refresh:
            continue  # already complete and not forcing a refresh

        # on refresh, recompute title/summary/status/type/updated from the body;
        # otherwise keep whatever the frontmatter already has and only fill gaps.
        # `created` is never overwritten once set.
        force = {"title", "summary", "status", "type", "updated"} if refresh else set()
        final = {}
        for k in CORE_KEYS:
            cur = fm_get(fm, k)
            final[k] = derived[k] if (k in force or cur is None) else cur
        final["created"] = fm_get(fm, "created") or derived["created"]

        # preserve any non-core frontmatter keys verbatim (e.g. supersedes, deciders)
        extras = [ln for ln in fm.splitlines()
                  if (km := re.match(r"^([A-Za-z0-9_-]+)\s*:", ln)) and km.group(1) not in CORE_KEYS]

        new_lines = []
        for k in CORE_KEYS:
            v = yaml_quote(final[k]) if k in ("title", "summary") else final[k]
            new_lines.append(f"{k}: {v}")
        new_lines.extend(extras)

        new_fm = "\n".join(new_lines)
        new_text = f"---\n{new_fm}\n---\n{body}" if not body.startswith("\n") else f"---\n{new_fm}\n---{body}"
        changed += 1
        if write:
            path.write_text(new_text)
            print(f"{'refreshed' if refresh else 'backfilled'} {rel}")
        else:
            print(f"would {'refresh' if refresh else 'backfill'} {rel}  (status={final['status']})")
    verb = "refreshed" if refresh else "backfilled"
    print(f"\n{changed} file(s) {verb if write else 'need ' + ('refresh' if refresh else 'backfill')}")
    return 0


